import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");
const modulePaths = [
  "src/model.mjs",
  "src/fixtures.mjs",
  "src/matching.mjs",
  "src/io.mjs",
  "src/i18n.mjs",
  "src/core.mjs",
];

export async function buildBundle() {
  const chunks = [];
  for (const modulePath of modulePaths) {
    const source = await readFile(resolve(root, modulePath), "utf8");
    const body = source
      .replace(/^import\s+[\s\S]*?\bfrom\s+["'][^"']+["'];\s*$/gm, "")
      .replace(/^export\s+(?=(?:const|let|function|class)\b)/gm, "");
    chunks.push(`// ${modulePath}\n${body.trim()}\n`);
  }
  return `/* Generated by scripts/build.mjs from src/*.mjs. Do not edit. */\nglobalThis.PriceConsoleCore = (() => {\n"use strict";\n${chunks.join("\n")}\nreturn PriceConsole;\n})();\n`;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const bundle = await buildBundle();
  const output = resolve(root, "dist/core.js");
  await mkdir(dirname(output), { recursive: true });
  await writeFile(output, bundle, "utf8");
  process.stdout.write(`Built ${output}\n`);
}
