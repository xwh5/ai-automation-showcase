export function t(language, key, variables = {}) {
  const dictionary = COPY[language] ?? COPY.en;
  const template = dictionary[key] ?? COPY.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(variables[name] ?? `{${name}}`));
}

export function textFor(language, value) {
  if (!value) return "";
  if (typeof value === "string") return value;
  return value[language] ?? value.en ?? value.zh ?? "";
}

export function categoryLabel(language, category) {
  const key = `category${String(category).charAt(0).toUpperCase()}${String(category).slice(1)}`;
  return t(language, key);
}

export function basisLabel(language, basis) {
  const key = `basis${String(basis).charAt(0).toUpperCase()}${String(basis).slice(1)}`;
  return t(language, key);
}

export function outcomeLabel(language, outcome) {
  const suffix = String(outcome).split("_").map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join("");
  return t(language, `outcome${suffix}`);
}

export function translationKeys() {
  return Object.keys(COPY.en);
}
